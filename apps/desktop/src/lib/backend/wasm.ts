// --- Asset-layout contract ------------------------------------------
//
// This module needs two things to exist as real HTTP-fetchable assets,
// at runtime, relative to the extension origin root (`chrome-extension://
// <id>/...` — a leading `/` below resolves against that origin from any
// page inside the extension, regardless of how deeply nested the page
// itself is). `apps/extension/scripts/build-spa.sh` is what actually
// wires this up today: it builds this app with `VITE_BACKEND=wasm`, then
// merges the result into `apps/extension/dist/` on top of what
// `apps/extension`'s own `vite.config.js`/`copy-vendor.sh` already put
// there (see that script's header for the full pipeline, and
// `apps/desktop/src/hooks.ts` for the `reroute` fix that makes the merged
// `index.html` actually resolve to this app's `/` route once loaded from
// `chrome-extension://<id>/index.html`):
//
//   1. `/pdfium.js` (+ the `/pdfium.wasm` it fetches itself) — PDFium's
//      Emscripten glue, vendored from pdfium-lib and copied into the
//      extension's dist by `apps/extension/scripts/copy-vendor.sh`. Must
//      be reachable as a classic (non-module) script — see
//      `loadPdfiumScript` below for why this file injects a <script> tag
//      itself instead of relying on some HTML shell's static <script>
//      tag (which this module doesn't get to assume exists, or ran
//      before this code did).
//   2. `/wasm-gen/openpdfedit_wasm.js` (+ its paired
//      `openpdfedit_wasm_bg.wasm`, which the glue module fetches relative
//      to its own URL — no separate reference needed here) — the
//      wasm-bindgen `--target web` output of `crates/openpdfedit-wasm`,
//      generated by `apps/extension/scripts/build-wasm.sh` into
//      `apps/extension/src/wasm-gen/`. This module imports it by a
//      **runtime** relative-URL string (see `WASM_GLUE_MODULE_PATH`
//      below), not a static `import` — the file does not exist anywhere
//      under `apps/desktop` (this app doesn't run `build-wasm.sh`; it
//      only ever gets copied into the merged `apps/extension/dist/`
//      output), so a static/literal specifier would fail both
//      `npm run check` and every `vite build` in this app, the same
//      failure `index.ts`'s own doc comment documents for a
//      `/* @vite-ignore */`-routed specifier. Routing through a `const`
//      variable + `/* @vite-ignore */` here is the right tool for the
//      opposite reason `index.ts` rejected it for its *own* import of
//      this file: `index.ts` needs Vite to actually resolve and bundle
//      `wasm.ts` for real (a literal specifier), while this import must
//      stay a genuine, unresolved-at-build-time runtime import, because
//      the target file never exists in `apps/desktop`'s own build output
//      — only in the merged extension `dist/` this app's build result
//      gets copied into.
//
// Neither dynamic import below is ever reached by `apps/desktop`'s own
// build or typecheck (see `initSession`'s doc for how `npm run check`/
// `VITE_BACKEND=wasm npm run build` both stay green without ever running
// this module's init sequence) — they only resolve for real once this
// app's build output is merged into `apps/extension/dist/` by
// `build-spa.sh` and loaded as the unpacked extension.
