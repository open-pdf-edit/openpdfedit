// --- Init sequence: PDFium's wasm module -> the wasm-bindgen glue's own
// init -> initialize_pdfium_render -> construct WasmSession. Moved here
// from `apps/extension/editor.ts` (which Task 9 retires), same ordering
// and the same hard-won comments about why each step is what it is — see
// that file's header for the fuller archaeology (which JS/wasm asset
// pair, why `init()`'s return value is the right second argument for
// `initialize_pdfium_render`) that isn't repeated verbatim here. --------

/** Injects PDFium's Emscripten glue as a classic (non-module) `<script>`
 * tag and waits for it to run. Not a static `<script>` tag in some HTML
 * shell this module can assume exists (unlike `editor.html` today) —
 * per task-8-brief.md point 4, this module owns the whole init sequence
 * itself rather than relying on HTML script ordering Task 9 hasn't
 * designed yet. A classic script (not `type="module"`) is required
 * because `pdfium.js` is Emscripten's "MODULARIZE=1 EXPORT_NAME=
 * PDFiumModule" UMD output — its top-level `var PDFiumModule = ...`
 * only becomes `window.PDFiumModule` when it runs as a non-module
 * script. */
function loadPdfiumScript(): Promise<void> {
  return new Promise((resolve, reject) => {
    const script = document.createElement("script");
    script.src = PDFIUM_SCRIPT_PATH;
    script.onload = () => resolve();
    script.onerror = () =>
      reject(
        new Error(
          `failed to load ${PDFIUM_SCRIPT_PATH} — see wasm.ts's asset-layout doc comment for what Task 9 needs to serve here`,
        ),
      );
    document.head.appendChild(script);
  });
}

let sessionPromise: Promise<WasmSessionHandle> | null = null;

/** Runs the init sequence exactly once (subsequent calls return the same
 * in-flight/settled promise) and returns the live `WasmSession`. Lazy
 * rather than run at module-evaluation time: this module has no
 * top-level `await` (the same constraint `index.ts` already documents —
 * `apps/desktop`'s configured esbuild target doesn't support it, and
 * this file is bundled by the exact same Vite config as `index.ts` when
 * `VITE_BACKEND=wasm`, so the constraint applies here too, not just
 * there), and every `Backend` method below calls this before touching
 * the session, so callers never have to think about init ordering
 * themselves. This is also what keeps `npm run check` and both
 * `vite build` directions green without ever loading real PDFium/wasm
 * assets: nothing at module scope calls this function, so neither
 * typecheck nor a production build ever executes `loadPdfiumScript`/the
 * dynamic imports below — they only run if something actually calls a
 * `wasmBackend` method at runtime, which no build or check step does. */
function ensureSession(): Promise<WasmSessionHandle> {
  if (!sessionPromise) {
    sessionPromise = initSession();
  }
  return sessionPromise;
}

async function initSession(): Promise<WasmSessionHandle> {
  await loadPdfiumScript();
  if (!window.PDFiumModule) {
    throw new Error(
      `${PDFIUM_SCRIPT_PATH} loaded but never defined window.PDFiumModule — wrong pdfium.js variant (see wasm.ts's asset-layout doc: it must be the classic-script "MODULARIZE=1 EXPORT_NAME=PDFiumModule" build, not pdfium.esm.js/pdfium.std.js)`,
    );
  }
  const pdfiumModule = await window.PDFiumModule();

  // Non-literal specifier + @vite-ignore: see the asset-layout comment
  // at the top of this file for why this particular import must stay
  // unresolved by the bundler (the opposite of index.ts's import of this
  // module, which must resolve for real).
  const wasmGluePath = WASM_GLUE_MODULE_PATH;
  const mod = (await import(/* @vite-ignore */ wasmGluePath)) as WasmModuleExports;
  const rustModule = await mod.default();

  // `rustModule` (i.e. `mod.default()`'s resolved value, the wasm-bindgen
  // `--target web` glue's `init()` return) has to be the *raw*
  // `WebAssembly.Instance.exports` object here, not some higher-level
  // wrapper — pdfium-render internally does `Reflect::get(local_module,
  // local_function_name)` to pull a named export off it and installs that
  // straight into Pdfium's own WASM indirect function table, which only
  // works if what comes back is the actual low-level exported function.
  // Under `--target web`, `openpdfedit_wasm.js`'s generated `init()` does
  // exactly `wasm = instance.exports; ...; return wasm;`, so `rustModule`
  // here already has that shape — no further unwrapping needed.
  //
  // This crate (pdfium-render 0.9.3) only name-installs one function this
  // way: `"write_block_from_callback_wasm"` (`wasm_bindings.rs` lines
  // 1808 and 1885, both on the write path) — `read_block_from_callback_wasm`
  // is `#[wasm_bindgen]`-exported (so it's present on `rustModule`/on
  // `InitOutput` in the generated `.d.ts`, 4-arg vs. the write path's
  // 3-arg) but never looked up by name anywhere in this crate version.
  // The write path only matters for `WasmSession::saveToBytes`'s
  // `FPDF_SaveAsCopy`/`FPDF_SaveWithVersion` call; `openDocument` goes
  // through `FPDF_LoadMemDocument64`, which copies the PDF bytes directly
  // and never touches the read/write-callback function-table machinery at
  // all — so `rustModule` being correct here is enough for every path
  // this backend actually exercises today.
  //
  // This is a summary, not the full investigation: the original read
  // pdfium-render 0.9.3's own source line-by-line to confirm the above
  // (which call sites, which arg counts, which path was actually
  // exercised) rather than assuming it from the API surface alone — see
  // `apps/extension/editor.ts` in the git history of commit `9e42968`
  // (the commit that deleted it, superseded by this file) for that
  // fuller archaeology if a future debugging session needs more than
  // this summary.
  const ok = mod.initialize_pdfium_render(pdfiumModule, rustModule, false);
  if (!ok) {
    throw new Error(
      "initialize_pdfium_render failed — pdfium.js/pdfium.wasm and the wasm-bindgen glue must be the matching build produced together by apps/extension/scripts/build-wasm.sh",
    );
  }

  return new mod.WasmSession();
}

